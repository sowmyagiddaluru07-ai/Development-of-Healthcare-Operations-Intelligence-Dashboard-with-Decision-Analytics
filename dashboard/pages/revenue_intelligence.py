"""Revenue Intelligence Page for Medical Operations Intelligence."""
import streamlit as st
import pandas as pd
from dashboard.components import (
    render_kpi_row,
    create_line_chart,
    create_bar_chart,
    create_pie_chart
)
from analytics.revenue_analytics import RevenueAnalytics


def render_revenue_intelligence(db, filters):
    st.title("💰 Revenue Intelligence & Financial Analytics")
    facility_id = filters.get("facility")
    department_id = filters.get("department")

    try:
        analytics = RevenueAnalytics(db)

        # 1. Summary KPIs
        st.subheader("💵 Financial Overview")
        summary = analytics.get_revenue_summary(facility_id, department_id)

        render_kpi_row([
            {"title": "Total Billed Revenue", "value": f"{summary.get('total_billed', 0):,.2f}", "prefix": "$"},
            {"title": "Total Paid Revenue", "value": f"{summary.get('total_paid', 0):,.2f}", "prefix": "$"},
            {"title": "Outstanding AR", "value": f"{summary.get('total_outstanding', 0):,.2f}", "prefix": "$"},
            {"title": "Collection Rate", "value": f"{summary.get('collection_rate', 0):.1f}", "suffix": "%"}
        ])

        st.markdown("---")

        
        # 2. Daily & Monthly Revenue Trends
        col1, col2 = st.columns(2)

        with col1:
            st.subheader("📈 Daily Revenue Collection")
            daily = analytics.get_daily_revenue(days=30, facility_id=facility_id)

            if daily:
                df_daily = pd.DataFrame(daily)
                st.plotly_chart(
                    create_line_chart(
                        df_daily,
                        x="date",
                        y="revenue",
                        title="Daily Revenue Collection",
                    ),
                    use_container_width=True,
                )
            else:
                st.info("No daily revenue data available.")

        with col2:
            st.subheader("📊 Monthly Revenue vs Outstanding")
            monthly = analytics.get_monthly_revenue(
                months=6, facility_id=facility_id
            )

            if monthly:
                df_monthly = pd.DataFrame(monthly)
                st.plotly_chart(
                    create_bar_chart(
                        df_monthly,
                        x="month",
                        y="revenue",
                        title="Monthly Revenue",
                    ),
                    use_container_width=True,
                )
            else:
                st.info("No monthly revenue data available.")

        st.markdown("---")

        # 3. Payment Method & Outstanding Aging Buckets
        col3, col4 = st.columns(2)

        
        with col3:
            st.subheader("💳 Revenue by Payment Method")
            payment = analytics.get_payment_analysis(facility_id)
            if payment:
                df_pay = pd.DataFrame(payment)
                st.plotly_chart(
                    create_pie_chart(
                        df_pay,
                        names="status",
                        values="amount",
                        title="Revenue by Payment Status",
                    ),
                    use_container_width=True,
                )
            else:
                st.info("No payment data available.")

        
        with col4:
            st.subheader("⏳ Outstanding AR Aging Buckets")
            aging = analytics.get_outstanding_analysis(facility_id)

            if aging:
                df_aging = pd.DataFrame(aging)
                st.write("Outstanding receivables data")
                st.dataframe(df_aging, use_container_width=True)
            else:
                st.info("No outstanding receivables data available.")


        st.markdown("---")

        
        # 4. Top Revenue Generating Doctors
        st.subheader("🏆 Top Revenue Generating Doctors")
        by_doc = analytics.get_revenue_by_doctor(facility_id)

        if by_doc:
            df_doc = pd.DataFrame(by_doc[:10])
            st.plotly_chart(
                create_bar_chart(
                    df_doc,
                    x="doctor",
                    y="revenue",
                    title="Revenue Generated by Doctor ($)",
                ),
                use_container_width=True,
            )
        else:
            st.info("No doctor revenue data available.")

    except Exception:
        st.error("Error loading Revenue Intelligence:")
        st.exception(__import__("sys").exc_info()[1])